#!/usr/bin/env bash
# Regenerates contracts/postgres/schema.sql from a database that Flyway has migrated.
#
# The migrations under backend/contracts/src/main/resources/db/migration/ are the executable
# form of the schema and carry the design rationale in comments. This file is the *applied*
# result — what pg_dump sees after every migration has run — and it is what CI diffs against,
# so a migration that changes a table without a contract bump fails the build.
#
#   ./tools/dump-schema.sh                      # uses ADVENTWAVE_DB_* or the local defaults
set -euo pipefail

HOST="${ADVENTWAVE_DB_HOST:-localhost}"
PORT="${ADVENTWAVE_DB_PORT:-5433}"
USER="${ADVENTWAVE_DB_USER:-adventwave}"
DB="${ADVENTWAVE_DB_NAME:-adventwave}"
OUT="$(cd "$(dirname "$0")/../.." && pwd)/contracts/postgres/schema.sql"

{
  cat <<'HEADER'
-- AdventWave PostgreSQL contract — applied schema snapshot.
--
-- GENERATED by backend/tools/dump-schema.sh. Do not edit by hand.
--
-- Source of the design (and of every comment explaining a decision) is the Flyway migration
-- backend/contracts/src/main/resources/db/migration/V1__core_schema.sql. This file is the
-- result of applying every migration to PostgreSQL 16 and dumping the schema: it is what a
-- consumer can rely on, and what CI compares a freshly migrated database against.
--
-- Excluded: flyway_schema_history (Flyway bookkeeping, not a contract), ownership, privileges.
--
HEADER
  PGPASSWORD="${ADVENTWAVE_DB_PASSWORD:-}" pg_dump -h "$HOST" -p "$PORT" -U "$USER" -d "$DB" \
      --schema-only --no-owner --no-privileges --exclude-table=flyway_schema_history \
    | grep -vE '^(--|SET |SELECT pg_catalog|\\restrict|\\unrestrict)' \
    | grep -vE '^\s*$'
} > "$OUT"

echo "wrote $OUT ($(grep -cE '^CREATE (TABLE|INDEX|TRIGGER|EXTENSION|FUNCTION)|^ALTER TABLE.*ADD CONSTRAINT' "$OUT") DDL statements)"
